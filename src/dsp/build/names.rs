/// The ugen named `name`.
#[must_use]
pub fn ugen_named(name: &str) -> Option<UGenSpec> {
    UGENS
        .iter()
        .find(|(n, _)| *n == name)
        .map(|(_, s)| s.clone())
}

/// True for a ugen whose first positional input is an audio input.
#[must_use]
pub fn is_processor(spec: &UGenSpec) -> bool {
    matches!(
        spec,
        UGenSpec::Lpf
            | UGenSpec::Hpf
            | UGenSpec::Bpf
            | UGenSpec::Delay
            | UGenSpec::Comb
            | UGenSpec::Ladder
            | UGenSpec::Svf
            | UGenSpec::FmMod
            | UGenSpec::Mul
            | UGenSpec::Add
    )
}

