//! Adapters between engine context and effect APIs.
use super::FxCtx;
use crate::dsp::caps::CapabilitySet;
use crate::dsp::graph;
use music_things_fx::{FxContext, GrainLimits};

/// Copies granular limits from engine capabilities.
pub fn grain_limits(caps: &CapabilitySet) -> GrainLimits {
    GrainLimits {
        max_grain_density: caps.max_grain_density,
        max_grain_size: caps.max_grain_size,
        max_capture_seconds: caps.max_capture_seconds,
    }
}
impl FxContext for FxCtx<'_> {
    fn fx_ctx(&mut self) -> music_things_fx::FxCtx<'_> {
        music_things_fx::FxCtx {
            sr: self.sr,
            samples: self.store,
            fft: self.fft,
            limits: grain_limits(self.caps),
            scratch: &mut *self.scratch,
            analysis: &mut *self.analysis,
            stats: &mut *self.stats,
        }
    }
}
impl From<graph::AnalyzerKind> for music_things_fx::AnalyzerKind {
    fn from(value: graph::AnalyzerKind) -> Self {
        match value {
            graph::AnalyzerKind::Level => Self::Level,
            graph::AnalyzerKind::Spectrum => Self::Spectrum,
            graph::AnalyzerKind::Spectrogram => Self::Spectrogram,
            graph::AnalyzerKind::NoteSpectrogram => Self::NoteSpectrogram,
            graph::AnalyzerKind::Oscilloscope => Self::Oscilloscope,
            graph::AnalyzerKind::PitchMeter => Self::PitchMeter,
            graph::AnalyzerKind::StereoMeter => Self::StereoMeter,
        }
    }
}
